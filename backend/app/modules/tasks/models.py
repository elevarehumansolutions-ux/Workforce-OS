"""ORM models for Cluster 6 (Task).

Contains :class:`Task` — one unit of work assigned to an employee, either
standalone (a manager typing "follow up with the vendor") or, from M11 on,
generated by a workflow step.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import UUID, CheckConstraint, DateTime, ForeignKey, Index, Integer, String, Text, text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import BaseModel
from .enums import BlockCategory, ReviewStatus, TaskStatus


class Task(BaseModel):
    """A unit of work with an owner, a deadline and, optionally, a KPI.

    Organization-scoped (RLS restricts rows to the caller's current org) and
    soft-deletable.

    ``department_id`` is the department that *does the work*, which can
    differ from the creator's own department (a Sales manager asking
    Dispatch for something); the creator is recorded separately in
    ``created_by_user_id``. ``kpi_id``, when set, links the task to the KPI
    it counts toward and so to that KPI's weight.

    "Overdue" is **not stored**: it is derived (``status`` open or in
    progress and ``due_at`` in the past), as is lateness (``completed_at``
    after ``due_at``), both from the timestamps already on the row. A
    cancelled task counts neither as completed nor as late. ``completed_at``
    is set exactly when the status is ``completed``, and ``cancel_reason``
    exactly when it is ``cancelled``, each enforced by a CHECK.

    ``workflow_instance_id`` and ``workflow_step_id`` are plain nullable
    columns with **no foreign key** for now: the tables they point at are
    M11's and do not exist yet, so M11's migration adds the constraints
    (every existing value is null, nothing to backfill). There are no ORM
    relationships on this model, deliberately: the service layer does its
    own lookups, which avoids lazy-load surprises under the async session.
    See 08_DECISIONS.md 2026-10-07.
    """

    __tablename__ = "tasks"

    __table_args__ = (
        CheckConstraint(
            f"status IN {tuple(s.value for s in TaskStatus)}",
            name="check_task_status",
        ),
        CheckConstraint(
            "(status = 'completed' AND completed_at IS NOT NULL)"
            " OR (status <> 'completed' AND completed_at IS NULL)",
            name="check_task_completed_at_matches_status",
        ),
        CheckConstraint(
            "(status = 'cancelled' AND cancel_reason IS NOT NULL)"
            " OR (status <> 'cancelled' AND cancel_reason IS NULL)",
            name="check_task_cancel_reason_matches_status",
        ),
        CheckConstraint(
            "approved_blocked_seconds >= 0",
            name="check_task_approved_blocked_seconds_not_negative",
        ),
        Index("idx_tasks_assignee_status", "organization_id", "assigned_to_employee_id", "status"),
        Index("idx_tasks_department_status", "organization_id", "department_id", "status"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id"),
        nullable=False,
        index=True,
        doc="Organization this task belongs to",
    )

    workflow_instance_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        doc="Running workflow this task came from; null = standalone. No FK until M11 creates the table",
    )

    workflow_step_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        doc="Workflow step this task came from; null = standalone. No FK until M11 creates the table",
    )

    department_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("departments.id"),
        nullable=False,
        index=True,
        doc="Department that does the work (may differ from the creator's own)",
    )

    kpi_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("kpis.id"),
        nullable=True,
        index=True,
        doc="KPI this task counts toward; null = not linked to a KPI",
    )

    assigned_to_employee_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("employees.id"),
        nullable=True,
        index=True,
        doc="Employee responsible for the task; null = in the department queue, unassigned",
    )

    title: Mapped[str] = mapped_column(
        Text, nullable=False, doc="Short name of the task"
    )

    description: Mapped[str | None] = mapped_column(
        Text, nullable=True, doc="Longer description of what is to be done"
    )

    due_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="Deadline. Never moved by a system event; only edited deliberately by an authorized person",
    )

    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="When it was completed; set exactly when status is 'completed'",
    )

    overdue_notified_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc=(
            "When the 'task is overdue' notification was sent; null = not sent yet. "
            "Cleared whenever the deadline changes, so a new deadline gets its own alert"
        ),
    )

    blocked_since: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="When the current block started; null = the task is not blocked right now",
    )

    approved_blocked_seconds: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
        doc=(
            "Total blocked time a reviewer has approved. Added to due_at when judging "
            "whether the task is overdue; due_at itself is never changed"
        ),
    )

    cancel_reason: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        doc="Why it was cancelled; set exactly when status is 'cancelled'",
    )

    status: Mapped[TaskStatus] = mapped_column(
        String(20),
        nullable=False,
        default=TaskStatus.OPEN.value,
        server_default=TaskStatus.OPEN.value,
        doc="open, in_progress, completed or cancelled; 'overdue' is derived, never stored",
    )

    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id"),
        nullable=True,
        doc="User who created the task; null for a workflow-generated task",
    )

    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
        doc="Soft delete timestamp: non-null means the task is deleted.",
    )


class TaskBlock(BaseModel):
    """One period during which a task could not move forward, and what a reviewer decided.

    Example: Chidi's task waits on Finance from Wednesday to Thursday. That is
    one row: ``blocked_at`` Wednesday, ``unblocked_at`` Thursday, category
    ``awaiting_other_department``. While ``unblocked_at`` is empty the task is
    blocked right now. A reviewer then approves or rejects it; only an approved
    block gives the time back (see ``Task.approved_blocked_seconds``).

    A task can be blocked many times over its life but only once at a time.
    ``blocked_at`` is always the moment the row was recorded, never backdated,
    so a block recorded after the deadline passed is plainly visible as late.
    Organization-scoped (RLS). See 08_DECISIONS.md 2026-10-09.
    """

    __tablename__ = "task_blocks"

    __table_args__ = (
        CheckConstraint(
            f"category IN {tuple(c.value for c in BlockCategory)}",
            name="check_task_block_category",
        ),
        CheckConstraint(
            f"review_status IN {tuple(s.value for s in ReviewStatus)}",
            name="check_task_block_review_status",
        ),
        CheckConstraint(
            "unblocked_at IS NULL OR unblocked_at >= blocked_at",
            name="check_task_block_unblocked_after_blocked",
        ),
        # A reviewed block must say who reviewed it and when; a pending one must not.
        CheckConstraint(
            "(review_status = 'pending' AND reviewed_by_user_id IS NULL AND reviewed_at IS NULL)"
            " OR (review_status <> 'pending' AND reviewed_by_user_id IS NOT NULL"
            " AND reviewed_at IS NOT NULL)",
            name="check_task_block_review_fields_match_status",
        ),
        # At most one open block (no unblocked_at yet) per task.
        Index(
            "uq_task_blocks_one_open_per_task",
            "task_id",
            unique=True,
            postgresql_where=text("unblocked_at IS NULL"),
        ),
        Index("idx_task_blocks_org_review", "organization_id", "review_status"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id"),
        nullable=False,
        index=True,
        doc="Organization this block belongs to",
    )

    task_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tasks.id"),
        nullable=False,
        index=True,
        doc="The task that was blocked",
    )

    blocked_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id"),
        nullable=False,
        doc="The user who recorded the block (the task's assignee)",
    )

    category: Mapped[BlockCategory] = mapped_column(
        String(30), nullable=False, doc="Why the task is blocked, picked from a short list"
    )

    reason: Mapped[str] = mapped_column(Text, nullable=False, doc="The assignee's explanation")

    blocked_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=text("now()"),
        doc="When the block was recorded. Never backdated",
    )

    unblocked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="When the block ended; null = the task is still blocked",
    )

    review_status: Mapped[ReviewStatus] = mapped_column(
        String(20),
        nullable=False,
        default=ReviewStatus.PENDING.value,
        server_default=ReviewStatus.PENDING.value,
        doc="pending, approved or rejected",
    )

    reviewed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id"),
        nullable=True,
        doc="The user who approved or rejected it; null while pending",
    )

    reviewed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="When it was reviewed; null while pending",
    )
